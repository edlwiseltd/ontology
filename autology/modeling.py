"""Model design support for Studio (R2, Studio increment 2): drafts, validation, discovery questions, proposals.

* **Drafts** are versioned copies of a use case's ontology document, kept in the store (append-only). A draft is
  never active: the engine keeps running the configured ontology. Making a draft active needs releases (REL-1).
* **Validation** runs the engine's own strict loader (MOD-1) on a document and locates the problem (a JSON path
  such as ``entities.Pump.attributes.flow``) so a UI can anchor it to a node or an edge. The loader stops at the
  first blocking problem: one problem is reported at a time.
* **Discovery questions** are derived from real gaps in a document and the use case's configuration (an entity
  with no relationship, a reviewer role nobody holds, a capability no tool provides, an action whose repeat
  safety is undeclared...). They are rule-based, not generated by a model.
* **Proposals** turn a business brief into typed, provisional additions. The only generator today is
  ``blueprint``: it matches the brief against approved industry blueprints (synthetic, no customer data) and is
  labelled ``"ai": false``. A model-based generator plugs into :func:`propose` once providers are decided (D7, D10).
  Proposals are never applied by the engine: a person accepts items into a draft, and the draft is validated.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Tuple

from .ontology import Ontology, OntologyError

BLUEPRINTS = Path(__file__).resolve().parent / "blueprints"
_PATH = re.compile(r"^([A-Za-z_][\w\-]*(?:\.[\w\-]+)*): (.*)$", re.S)


def locate(path: str) -> Dict[str, Any]:
    """Where a problem path points in a model: an entity (node), a relationship (edge index) or another part."""
    parts = path.split(".")
    if len(parts) >= 2 and parts[0] in ("entities", "interfaces"):
        return {"node": parts[1], "field": ".".join(parts[2:]) or None}
    if len(parts) >= 2 and parts[0] == "relationships" and parts[1].isdigit():
        return {"edge": int(parts[1])}
    if len(parts) >= 2 and parts[0] in ("actions", "goals", "functions", "case_templates"):
        return {"section": parts[0], "name": parts[1]}
    if len(parts) >= 2 and parts[0] == "rules" and parts[1].isdigit():
        return {"section": "rules", "index": int(parts[1])}
    return {}


def validate(document: Any) -> Dict[str, Any]:
    """Run the engine's strict loader on ``document``; never changes anything."""
    if not isinstance(document, dict):
        return {"valid": False, "problems": [{"path": "", "message": "an ontology document must be a JSON object"}]}
    try:
        onto = Ontology.from_dict(document)
    except OntologyError as exc:
        text = str(exc)
        m = _PATH.match(text)
        known = ("entities", "interfaces", "relationships", "actions", "rules", "goals", "settings", "functions",
                 "case_templates", "competency_questions", "impact_rules", "scheduling")
        path, message = (m.group(1), m.group(2)) if m and m.group(1).split(".")[0] in known else ("", text)
        where = locate(path)
        named = re.search(r"\bentity '([^']+)'", message)
        if not where and named:  # messages without a path that name an entity still point at its node
            where = {"node": named.group(1)}
        return {"valid": False, "problems": [{"path": path, "message": message, **where}],
                "note": "validation stops at the first blocking problem; fix it and validate again"}
    return {"valid": True, "problems": [], "ref": onto.ref, "fingerprint": onto.fingerprint,
            "summary": {"entities": len(onto.entities), "relationships": len(onto.relationships),
                        "actions": len(onto.actions), "rules": len(onto.rules)}}


def questions(document: Any, service: Any = None) -> List[Dict[str, Any]]:
    """Questions that come from real gaps in this model and this use case (rule-based, not AI)."""
    if not isinstance(document, dict):
        return []
    out: List[Dict[str, Any]] = []
    entities = document.get("entities") or {}
    rels = [r for r in (document.get("relationships") or []) if isinstance(r, dict)]
    linked = {r.get("from") for r in rels} | {r.get("to") for r in rels}
    for name in sorted(entities):
        if len(entities) > 1 and name not in linked:
            out.append({"id": f"isolated:{name}", "kind": "relationship", "node": name, "severity": "medium",
                        "question": f"How is {name} related to the rest of the model?",
                        "why": f"{name} has no relationship: no case can reach it from another record",
                        "evidence": "the business link (which record owns or references it)"})
    held: set = set()
    capabilities: set = set()
    if service is not None:
        held = set().union(*[u.reviewer_roles for u in service.users]) if service.users else set()
        for cfg in service.agents.values():
            for member in [cfg.agent] + cfg.agent.delegates:
                capabilities |= {t.capability for t in member.tools}
    for i, rule in enumerate(document.get("rules") or []):
        if isinstance(rule, dict) and rule.get("type") == "human_review" and rule.get("reviewer") \
                and rule["reviewer"] not in held:
            out.append({"id": f"reviewer:{rule['reviewer']}", "kind": "approval", "rule": i, "severity": "high",
                        "question": f"Who holds the reviewer role '{rule['reviewer']}' required by {rule.get('id', f'rule {i}')}?",
                        "why": "an approval with no named reviewer cannot happen (and blocks the pilot stage)",
                        "evidence": "a named member granted this reviewer role"})
    for name, action in sorted((document.get("actions") or {}).items()):
        if not isinstance(action, dict):
            continue
        cap = action.get("capability")
        if cap and cap not in capabilities:
            out.append({"id": f"capability:{cap}", "kind": "integration", "action": name, "severity": "high",
                        "question": f"Which system performs '{cap}' for {name}?",
                        "why": "no tool provides this capability: the action can never run",
                        "evidence": "the system, its environment (simulated, sandbox, production) and its owner"})
        if "side_effect" not in action:
            out.append({"id": f"side-effect:{name}", "kind": "safety", "action": name, "severity": "medium",
                        "question": f"Is it safe to repeat {name} if a call's outcome is unknown?",
                        "why": "undeclared actions are treated as unsafe to repeat (D8): a person must reconcile",
                        "evidence": "whether the target system deduplicates (idempotent) or has no side effect"})
    if entities and not (document.get("goals") or {}):
        out.append({"id": "goals", "kind": "goal", "severity": "medium",
                    "question": "What outcome should the agents pursue?",
                    "why": "without a goal no run can be planned", "evidence": "a target condition, e.g. a status"})
    return out


def blueprints() -> List[Dict[str, Any]]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(BLUEPRINTS.glob("*.json"))]


def match(brief: str) -> Tuple[Optional[Dict[str, Any]], List[str]]:
    """The approved blueprint whose vocabulary ``brief`` uses most (at least two terms), and the terms found."""
    words = set(re.findall(r"[a-z]+(?: order)?", brief.lower()))
    best: Optional[Dict[str, Any]] = None
    matched: List[str] = []
    for bp in blueprints():
        hits = sorted(k for k in bp["keywords"] if k in words or k in brief.lower())
        if len(hits) >= 2 and len(hits) > len(matched):
            best, matched = bp, hits
    return best, matched


_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")


def parameters(blueprint: Mapping[str, Any], answers: Optional[Mapping[str, Any]] = None
               ) -> Tuple[Dict[str, Any], List[str]]:
    """The values of a blueprint's parameters: an answer where one was given and fits the parameter's type, its
    default otherwise. Also returns the ids still on their default (the questions that remain open)."""
    values: Dict[str, Any] = {}
    open_ids: List[str] = []
    for spec in blueprint.get("parameters") or []:
        raw = (answers or {}).get(spec["id"])
        value: Any = None
        if isinstance(raw, (str, int, float)) and not isinstance(raw, bool) and str(raw).strip():
            text = str(raw).strip()
            if spec["type"] == "number":
                try:
                    number = float(text)
                    value = int(number) if number == int(number) else number
                except (ValueError, OverflowError):
                    value = None
            elif spec["type"] == "name":
                candidate = re.sub(r"[^A-Za-z0-9_]+", "_", text).strip("_").lower()
                value = candidate if _NAME.match(candidate) else None
            else:
                value = re.sub(r"[{}<>\x00-\x1f]", " ", text)[:120]
        if value is None:
            value = spec["default"]
            open_ids.append(spec["id"])
        values[spec["id"]] = value
    return values, open_ids


def fill(value: Any, values: Mapping[str, Any]) -> Any:
    """``value`` with every ``{parameter}`` in its strings replaced."""
    if isinstance(value, str):
        return re.sub(r"\{([a-z_]+)\}", lambda m: str(values.get(m.group(1), m.group(0))), value)
    if isinstance(value, list):
        return [fill(v, values) for v in value]
    if isinstance(value, dict):
        return {k: fill(v, values) for k, v in value.items()}
    return value


def propose(brief: str, document: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Provisional additions for ``brief``. Today: approved blueprints only (no AI). Nothing is applied."""
    document = document if isinstance(document, dict) else {}
    have_entities = set(document.get("entities") or {})
    have_actions = set(document.get("actions") or {})
    have_rels = {(r.get("from"), r.get("to"), r.get("type")) for r in document.get("relationships") or []
                 if isinstance(r, dict)}
    have_rules = {r.get("id") for r in document.get("rules") or [] if isinstance(r, dict)}
    have_goals = set(document.get("goals") or {})
    have_templates = set(document.get("case_templates") or {})
    best, matched = match(brief)
    if best is None:
        return {"generator": "blueprint", "ai": False, "items": [],
                "message": "no approved blueprint matches this brief; a model-based architect is not configured "
                           "(AI providers are an open decision, D7 and D10)"}
    items = []
    defaults, _ = parameters(best)
    for item in best["items"]:
        v = fill(item["value"], defaults)
        key = (item["kind"], item.get("name") or v.get("id") or f"{v.get('from')}-{v.get('type')}-{v.get('to')}")
        already = ((item["kind"] == "entity" and item["name"] in have_entities)
                   or (item["kind"] == "action" and item["name"] in have_actions)
                   or (item["kind"] == "relationship" and (v["from"], v["to"], v["type"]) in have_rels)
                   or (item["kind"] == "rule" and v.get("id") in have_rules)
                   or (item["kind"] == "goal" and item["name"] in have_goals)
                   or (item["kind"] == "case_template" and item["name"] in have_templates))
        if already:
            continue
        items.append({"id": f"{best['id']}:{key[0]}:{key[1]}", "kind": item["kind"], "name": item.get("name"),
                      "value": v, "rationale": item["rationale"], "status": "provisional",
                      "provenance": {"generator": "blueprint", "blueprint": best["id"], "ai": False,
                                     "matched_terms": matched}})
    return {"generator": "blueprint", "ai": False, "blueprint": {"id": best["id"], "name": best["name"]},
            "matched_terms": matched, "items": items,
            "message": "proposals from an approved industry blueprint (not AI); nothing is applied until you "
                       "accept items into the draft and it validates"}
