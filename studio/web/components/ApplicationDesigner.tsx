"use client";

// Studio's Application Designer: from what is released to a design of the application its users will open.
//   generate (the engine, deterministic) → inspect → arrange → validate (the engine) → preview → save a draft
// The designer arranges screens. It cannot write a rule, a permission or code: the manifest has no place for them,
// and the engine refuses anything it does not know. The preview is the same renderer the application uses.

import { useCallback, useEffect, useState } from "react";
import { application, ApiError, getToken, type AppCheck, type AppDraft } from "@/lib/api";
import { ACCENTS, BASIS_TEXT, basisCounts, describe, inNavigation, moveNavigation, renameNavigation, setAccent, setColumns,
  setTitle, toggleNavigation } from "@/lib/appdesign";
import { short, unsupportedViews } from "@/runtime/model";
import RuntimeApp from "@/runtime/RuntimeApp";
import type { Basis, Manifest } from "@/runtime/types";
import type { OntologySummary, UseCase } from "@/lib/types";

const BasisTag = ({ basis }: { basis: Basis }) => <span className={`badge basis-${basis}`} title={BASIS_TEXT[basis]}>{BASIS_TEXT[basis]}</span>;

export default function ApplicationDesigner({ workspace, useCase, admin, ontology }: {
  workspace: string; useCase: UseCase; admin: boolean; ontology: OntologySummary | null }) {
  const path = useCase.path;
  const [draft, setDraft] = useState<AppDraft | null>(null);
  const [manifest, setManifest] = useState<Manifest | null>(null);
  const [check, setCheck] = useState<AppCheck | null>(null);
  const [dirty, setDirty] = useState(false);
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");
  const [note, setNote] = useState("");
  const [selected, setSelected] = useState("");
  const [preview, setPreview] = useState<"" | "configuration" | "synthetic">("");

  const load = useCallback(async () => {
    setError("");
    try {
      const d = await application.draft(path);
      setDraft(d); setManifest(d.manifest); setCheck(d.validation); setDirty(false);
    } catch (e) { setError((e as Error).message); }
  }, [path]);
  useEffect(() => { void load(); }, [load]);

  const change = (next: Manifest) => { setManifest(next); setDirty(true); setCheck(null); setMessage(""); };
  const generate = async () => {
    setError(""); setMessage("");
    try {
      const out = await application.generate(path);
      setManifest(out.manifest); setCheck(out.validation); setDirty(true);
      setMessage(`Generated by the engine from what runs (${out.generator.kind}; no language model was asked). Nothing is saved yet.`);
    } catch (e) { setError((e as Error).message); }
  };
  const validate = async () => {
    if (!manifest) return;
    setError("");
    try { setCheck((await application.validate(path, manifest)).validation); } catch (e) { setError((e as Error).message); }
  };
  const save = async () => {
    if (!manifest || !draft) return;
    setError(""); setMessage("");
    try {
      const d = await application.save(path, manifest, draft.revision, note);
      setDraft(d); setManifest(d.manifest); setCheck(d.validation); setDirty(false); setNote("");
      setMessage(`Saved as design revision ${d.revision}. It is a draft for preview: it is not part of a governed release, and it runs nothing.`);
    } catch (e) {
      const err = e as ApiError;
      const problems = (err.data?.problems as { path: string; message: string }[] | undefined) ?? [];
      if (problems.length) setCheck({ valid: false, problems });
      setError(err.message);
    }
  };

  const view = manifest?.views.find((v) => v.id === selected) ?? null;
  const attributes = view?.entity && ontology?.entities[view.entity] ? ["status", ...Object.keys(ontology.entities[view.entity].attributes).filter((a) => a !== "status")] : [];
  const counts = manifest ? basisCounts(manifest) : null;
  const unsupported = manifest ? unsupportedViews(manifest) : [];
  const stale = !!(draft?.manifest && draft.validation && !draft.validation.valid);

  return (
    <div className="appdesign" data-testid="app-designer">
      <p className="notice small" role="note" data-testid="app-notice">
        An application is designed from <strong>what is released</strong>, never from a draft model. The design below is data the engine
        validates: it holds no rule, no permission and no code. Production: unavailable. Records are synthetic and tools are simulated.
      </p>
      {error && <p className="error" role="alert" data-testid="app-error">{error}</p>}
      {message && <p role="status" data-testid="app-message">{message}</p>}
      <div className="card">
        <div className="row spread">
          <div>
            <h3>Application design</h3>
            <p className="small muted" data-testid="app-state">
              {draft?.revision ? `Saved revision ${draft.revision} by ${draft.author}` : "No design saved yet"}
              {dirty ? " · unsaved changes" : ""} · what runs: {draft ? `${draft.running.model}, configuration ${short(draft.running.configuration)}` : "…"}
            </p>
          </div>
          <div className="row">
            <button type="button" onClick={generate} disabled={!admin} data-testid="app-generate">{manifest ? "Generate again from what runs" : "Generate from what runs"}</button>
            <button type="button" onClick={validate} disabled={!manifest} data-testid="app-validate">Validate with the engine</button>
          </div>
        </div>
        {stale && !dirty && <p className="warn" data-testid="app-stale">The saved design was made for another configuration than the one that runs now. The application is not shown to its users until a design made for what runs is saved: generate again, check it, save.</p>}
        {check && (
          <div data-testid="app-validation" className={check.valid ? "" : "error"}>
            <strong>{check.valid ? "The engine accepts this design for what runs." : `The engine refuses this design (${check.problems.length} problem(s)):`}</strong>
            {!check.valid && <ul>{check.problems.slice(0, 12).map((p, i) => <li key={i}><code>{p.path}</code> {p.message}</li>)}</ul>}
          </div>)}
        {unsupported.length > 0 && <p className="warn" data-testid="app-unsupported">Not supported by the renderer, and not shown to users: {unsupported.map((v) => `${v.title} (${v.type})`).join(", ")}</p>}
      </div>

      {manifest && (
        <>
          <div className="card" data-testid="app-settings">
            <div className="row">
              <div style={{ flex: 2 }}><label htmlFor="app-title">Title</label>
                <input id="app-title" value={manifest.title} maxLength={120} disabled={!admin} onChange={(e) => change(setTitle(manifest, e.target.value))} /></div>
              <div style={{ flex: 1 }}><label htmlFor="app-accent">Accent</label>
                <select id="app-accent" value={manifest.presentation.accent} disabled={!admin} onChange={(e) => change(setAccent(manifest, e.target.value))}>
                  {ACCENTS.map((a) => <option key={a} value={a}>{a}</option>)}</select></div>
            </div>
            <p className="small muted" data-testid="app-basis">Where the choices come from: {counts && (Object.keys(counts) as Basis[]).filter((b) => counts[b]).map((b) => `${counts[b]} ${BASIS_TEXT[b]}`).join(" · ")}</p>
            <p className="small muted">Meant for the roles: {manifest.roles.join(", ") || "—"}. This is information: the engine decides what each person sees and may do.</p>
          </div>

          <div className="card">
            <h3>Screens ({manifest.views.length}) and navigation ({manifest.navigation.length})</h3>
            <div className="rt-scroll">
              <table className="rt-table" data-testid="app-screens">
                <thead><tr><th scope="col">In navigation</th><th scope="col">Screen</th><th scope="col">Kind</th><th scope="col">Bound to</th><th scope="col">From</th><th scope="col">Order</th></tr></thead>
                <tbody>{manifest.views.map((v) => {
                  const nav = manifest.navigation.find((n) => n.view === v.id);
                  return (
                    <tr key={v.id} data-view={v.id} className={selected === v.id ? "selected" : ""}>
                      <td><input type="checkbox" aria-label={`${v.title} in navigation`} checked={inNavigation(manifest, v.id)} disabled={!admin}
                                 onChange={() => change(toggleNavigation(manifest, v.id))} style={{ width: "auto" }} /></td>
                      <td>{nav ? <input aria-label={`Label of ${v.id}`} value={nav.label} maxLength={120} disabled={!admin}
                                        onChange={(e) => change(renameNavigation(manifest, v.id, e.target.value))} style={{ margin: 0 }} /> : <span className="muted">{v.title}</span>}</td>
                      <td><button type="button" className="link" onClick={() => setSelected(v.id)}>{v.type}</button></td>
                      <td className="small">{describe(v)}</td>
                      <td><BasisTag basis={nav?.basis === "confirmed" ? "confirmed" : v.basis} /></td>
                      <td>{nav && <span className="row">
                        <button type="button" className="small" aria-label={`Move ${v.id} up`} disabled={!admin} onClick={() => change(moveNavigation(manifest, v.id, -1))}>↑</button>
                        <button type="button" className="small" aria-label={`Move ${v.id} down`} disabled={!admin} onClick={() => change(moveNavigation(manifest, v.id, 1))}>↓</button></span>}</td>
                    </tr>);
                })}</tbody>
              </table>
            </div>
          </div>

          {view && (
            <div className="card" data-testid="app-inspector">
              <h3>{view.title} <span className="muted small">{view.type} · {view.id}</span> <BasisTag basis={view.basis} /></h3>
              <p className="small muted">{describe(view)}</p>
              {view.type === "EntityListView" && (
                <fieldset data-testid="app-columns"><legend>Attributes shown as columns (of those the model has)</legend>
                  {attributes.map((a) => {
                    const on = (view.columns ?? []).some((c) => c.field === a);
                    return (<label key={a} className="row" style={{ display: "inline-flex", marginRight: 12 }}>
                      <input type="checkbox" checked={on} disabled={!admin} style={{ width: "auto", margin: 0 }} data-column={a}
                             onChange={() => change(setColumns(manifest, view.id, on ? (view.columns ?? []).filter((c) => c.field !== a).map((c) => c.field)
                               : [...(view.columns ?? []).map((c) => c.field), a]))} /> {a}</label>);
                  })}
                  <p className="small muted">A column shown here is still subject to the model&apos;s field rules: a person who may not read an attribute does not see it.</p>
                </fieldset>)}
              {(view.columns ?? view.fields ?? []).length > 0 && (
                <ul className="small">{(view.columns ?? view.fields ?? []).map((c) => <li key={c.field}><code>{view.entity}.{c.field}</code> as “{c.label}” <BasisTag basis={c.basis} /></li>)}</ul>)}
              {(view.related ?? []).length > 0 && <ul className="small">{(view.related ?? []).map((r) => <li key={r.relationship + r.direction + r.entity}>{r.label} <BasisTag basis={r.basis} /></li>)}</ul>}
              {(view.actions ?? []).length > 0 && (
                <ul className="small" data-testid="app-actions">{(view.actions ?? []).map((a) => (
                  <li key={a.action}><code>{a.action}</code>: {a.rules.length ? `rules ${a.rules.join(", ")}` : "no rule names it"} <BasisTag basis={a.basis} /></li>))}</ul>)}
              {view.type === "RecordFormView" && <p className="small warn">Forms are previews: saving a record from an application needs a permission that does not exist yet (owner decision D24).</p>}
            </div>)}

          <div className="card" data-testid="app-cannot">
            <h3>What the application will say it cannot do</h3>
            <ul className="small">{manifest.unavailable.map((u) => <li key={u.feature}>{u.reason}</li>)}</ul>
          </div>

          <div className="card">
            <h3>Preview</h3>
            <div className="row">
              <button type="button" onClick={() => setPreview(preview === "configuration" ? "" : "configuration")} data-testid="app-preview-config">Configuration preview</button>
              <button type="button" onClick={() => setPreview(preview === "synthetic" ? "" : "synthetic")} data-testid="app-preview-data">Synthetic-data preview</button>
              <a className="button" href={`/run/${encodeURIComponent(workspace)}/${encodeURIComponent(useCase.id)}`} target="_blank" rel="noreferrer" data-testid="app-open">
                Open the application (engine-backed simulation)</a>
              <span className="badge">Production: unavailable</span>
            </div>
            <p className="small muted">The preview is the application&apos;s own renderer, given this design. A configuration preview reads no record. A synthetic-data preview
              reads records with your own access (an administrator without a data grant sees none). The application itself opens at its own address, with its own sign-in.</p>
            {preview && <div className="app-preview" data-testid="app-preview"><RuntimeApp key={preview} workspace={workspace} useCase={useCase.id} preview={{ manifest, mode: preview, token: getToken }} /></div>}
          </div>

          <div className="card">
            <label htmlFor="app-note">What changed (optional)</label>
            <input id="app-note" value={note} maxLength={300} onChange={(e) => setNote(e.target.value)} />
            <button type="button" className="primary" onClick={save} disabled={!admin || !dirty} data-testid="app-save">Save as a design draft</button>
            {(draft?.history ?? []).length > 0 && (
              <ul className="small muted" data-testid="app-history">{draft?.history.map((h) => (
                <li key={h.revision}>revision {h.revision} · {h.author} · {h.at.slice(0, 16).replace("T", " ")} · for configuration {short(h.configuration)}{h.note ? ` · ${h.note}` : ""}</li>))}</ul>)}
          </div>
        </>)}
    </div>
  );
}
