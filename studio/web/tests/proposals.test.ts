import { describe, expect, it } from "vitest";
import { withProvenance } from "../lib/onboarding";
import { compareRevisions, decided, generatedBy, originLabel, outcomes, revisionLine, sessionLine, whyLines } from "../lib/proposals";
import type { Proposal, ProposalItem } from "../lib/types";

const item = (name: string, extra: Partial<ProposalItem> = {}): ProposalItem => ({
  id: `model:entity:${name}`, kind: "entity", name, value: { states: ["open"], attributes: {} }, rationale: "stated",
  status: "provisional", provenance: { generator: "model", ai: true }, basis: "supplied", origin: "brief",
  evidence: [{ ref: "brief", kind: "brief" }], confidence: 0.8, attention: [], ...extra } as ProposalItem);
const proposal = (revision: number, items: ProposalItem[], extra: Partial<Proposal> = {}): Proposal => ({
  id: "P-1", revision, latest_revision: 2, generator: "model", ai: true, provider: "anthropic", model: "claude-opus-5-5",
  message: "", items, answers: [], questions: [], decisions: [], history: [], drafts: [],
  source_index: { brief: { kind: "brief", text: "Coordinate vessel berthing." } }, ...extra } as Proposal);

describe("stored design sessions", () => {
  it("names who generated a revision and never calls a test double a model", () => {
    expect(generatedBy({ generator: "model", ai: true, provider: "anthropic", model: "claude-opus-5-5" })).toBe("anthropic · claude-opus-5-5");
    expect(generatedBy({ generator: "sandbox", ai: false, provider: "sandbox" })).toBe("test double (sandbox; not a language model)");
    expect(generatedBy({ generator: "blueprint", ai: false })).toContain("no language model");
    expect(generatedBy({ generator: "model", ai: true })).toBe("provider not recorded · model not recorded");
  });
  it("says what a session holds, what it already cost and where it led", () => {
    const line = sessionLine({ id: "P-1", brief: "b", revisions: 2, generator: "model", ai: true, provider: "anthropic",
      model: "claude-opus-5-5", decisions: 1, revision: 2, at: "2026-11-17T08:01:02Z", items: 40, open_questions: 0,
      spent_usd: 0.5046, drafts: [1, 2] } as any);
    expect(line).toBe("2 revisions · 40 element(s) · no open question · anthropic · claude-opus-5-5 · 0.5046 USD already spent · saved as draft revision 1, 2");
    expect(sessionLine({ id: "P-2", brief: "b", revisions: 1, generator: "sandbox", ai: false, provider: "sandbox", decisions: 0,
      revision: 1, at: "x", items: 3, open_questions: 2, spent_usd: 0, drafts: [] } as any))
      .toBe("1 revision · 3 element(s) · 2 open question(s) · test double (sandbox; not a language model)");
  });
  it("describes each revision with its author, its model and what was asked", () => {
    const line = revisionLine({ revision: 2, at: "2026-11-17T08:05:00+00:00", created_by: "ada", answers: [{}, {}], items: 40,
      rejected: 1, open_questions: 0, generator: "model", ai: true, provider: "anthropic", model: "claude-opus-5-5",
      cost_usd: 0.2886, feedback: "Add the berth." } as any);
    expect(line).toBe("revision 2 · 2026-11-17 08:05 · ada · anthropic · claude-opus-5-5 · 40 element(s), 1 refused, 0 open question(s) · 2 answer(s) · 0.2886 USD · asked: “Add the berth.”");
  });
});

describe("comparing two revisions", () => {
  const first = proposal(1, [item("Vessel"), item("Tug", { basis: "inferred", origin: "inference", evidence: [] }), item("Crane")],
    { questions: [{ id: "volume", question: "?", why: "" }, { id: "pilot", question: "?", why: "" }] as any });
  const second = proposal(2, [item("Vessel"), item("Berth", { origin: "answers", evidence: [{ ref: "answer:volume", kind: "answer" }] }),
    item("Tug", { confidence: 0.4 }), item("Crane", { value: { states: ["idle", "busy"], attributes: {} } })],
    { answers: [{ id: "volume", answer: "twelve a day" }], questions: [{ id: "pilot", question: "?", why: "" }, { id: "tide", question: "?", why: "" }] as any });
  it("finds what was added, removed and changed, and says how", () => {
    const d = compareRevisions(first, second);
    expect(d.added).toEqual(["entity Berth"]);
    expect(d.removed).toEqual([]);
    expect(d.changed).toEqual([
      { label: "entity Crane", what: ["definition"] },
      { label: "entity Tug", what: ["origin: the architect's inference · needs your confirmation → stated in your description",
                                     "basis: inferred → supplied", "confidence: 0.8 → 0.4"] }]);
    expect(d.unchanged).toBe(1);
    expect(d.answers).toEqual(["volume: twelve a day"]);
    expect((d.questionsClosed, d.questionsOpened)).toEqual(["tide"]);
    expect(d.questionsClosed).toEqual(["volume"]);
    expect(d.sameModel).toBe(true);
  });
  it("notices a revision generated by another model, and an identical revision", () => {
    expect(compareRevisions(first, proposal(2, first.items, { model: "another-model" })).sameModel).toBe(false);
    const same = compareRevisions(first, proposal(2, first.items, { questions: first.questions }));
    expect([same.added, same.removed, same.changed, same.unchanged]).toEqual([[], [], [], 3]);
    expect(compareRevisions(second, first).removed).toEqual(["entity Berth"]);
  });
});

describe("why an element was proposed", () => {
  const berth = item("Berth", { origin: "answers", evidence: [{ ref: "answer:volume", kind: "answer" }], rationale: "twelve calls need berths" });
  const p = proposal(2, [berth], {
    source_index: { brief: { kind: "brief", text: "Coordinate vessel berthing." },
                    "answer:volume": { kind: "answer", question: "How many vessels call each day?", text: "About twelve a day" } },
    decisions: [{ revision: 1, decided_by: "ada", at: "2026-11-17T08:00:00Z", accepted: [berth.id], rejected: [], note: "earlier revision" },
                { revision: 2, decided_by: "maria", at: "2026-11-17T09:00:00Z", accepted: [berth.id], rejected: [], note: "confirmed" }] });
  it("gives the reason, what is cited with its text, and what a person decided", () => {
    expect(whyLines(berth, p)).toEqual([
      "Reason given: twelve calls need berths",
      "Origin: from your answers",
      "Cites your answer to “How many vessels call each day?”: About twelve a day",
      "Accepted by maria on 2026-11-17 (confirmed)",
      "The architect's confidence: 0.8"]);
  });
  it("never invents a reference: unknown and uncited are said as they are", () => {
    const crane = item("Crane", { origin: "unknown", basis: "inferred", evidence: [], attention: ["cites a source that was not given"] });
    expect(whyLines(crane, p)).toEqual(["Reason given: stated",
      "Origin: origin not established · presented as given, but nothing given is cited", "Cites nothing that was given",
      "Note: cites a source that was not given", "The architect's confidence: 0.8"]);
    const lost = item("Gate", { evidence: [{ ref: "doc-9", kind: "source" }], origin: "sources" });
    expect(whyLines(lost, p)[2]).toBe("Cites doc-9 (its text is not kept with this revision)");
    expect(originLabel({ basis: "supplied" } as any)).toBe("from what you gave (cited)");
    expect(originLabel({ basis: "inferred" } as any)).toBe("inferred · needs your confirmation");
    expect(whyLines(item("Vessel"), p)[2]).toBe("Cites your description: Coordinate vessel berthing.");
  });
});

describe("where a proposal led, and what was decided", () => {
  it("links each draft saved from it to the releases made from that draft", () => {
    const p = proposal(2, [], { drafts: [{ draft_revision: 1, proposal_revision: 2, saved_by: "ada", at: "x" },
                                         { draft_revision: 3, proposal_revision: 2, saved_by: "ada", at: "y" }] });
    const releases = [{ number: 1, status: "superseded", design: { draft_revision: 1, proposal: { proposal: "P-1", revision: 2 } } },
                      { number: 2, status: "active", design: { draft_revision: 1, proposal: { proposal: "P-1", revision: 2 } } },
                      { number: 3, status: "proposed", design: { draft_revision: 1, proposal: { proposal: "P-other", revision: 1 } } },
                      { number: 4, status: "proposed", design: null }];
    expect(outcomes(p, releases)).toEqual([
      "revision 2 → draft revision 1 (saved by ada) → release 1 (superseded), release 2 (active)",
      "revision 2 → draft revision 3 (saved by ada) → not released"]);
    expect(outcomes(proposal(1, []), releases)).toEqual([]);
  });
  it("reads the decisions of the revision being read, the last one winning", () => {
    const p = proposal(2, [], { decisions: [
      { revision: 1, decided_by: "ada", at: "a", accepted: ["x"], rejected: [], note: "" },
      { revision: 2, decided_by: "ada", at: "b", accepted: ["a", "b"], rejected: ["c"], note: "" },
      { revision: 2, decided_by: "maria", at: "c", accepted: ["c"], rejected: ["a"], note: "" }] });
    const d = decided(p);
    expect([[...d.accepted].sort(), [...d.rejected].sort()]).toEqual([["b", "c"], ["a"]]);
  });
  it("carries what an element rests on into the draft, and says unknown when it was not established", () => {
    const doc = withProvenance({ name: "m", version: "0.1.0" } as any, proposal(2, []),
      [item("Berth", { origin: "answers", evidence: [{ ref: "answer:volume", kind: "answer" }] }),
       item("Old", { origin: undefined, basis: undefined, evidence: undefined })], "ada");
    const kept = (doc as any)["x-studio"].provenance;
    expect(kept["entity:Berth"]).toEqual({ proposal: "P-1", revision: 2, generator: "model", ai: true, provider: "anthropic",
      model: "claude-opus-5-5", basis: "supplied", origin: "answers", evidence: [{ ref: "answer:volume", kind: "answer" }], accepted_by: "ada" });
    expect([kept["entity:Old"].origin, kept["entity:Old"].basis, kept["entity:Old"].evidence]).toEqual(["unknown", "inferred", []]);
  });
});
